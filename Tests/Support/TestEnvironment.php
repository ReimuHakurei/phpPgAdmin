<?php

declare(strict_types=1);

namespace Tests\Support;

use Dotenv\Dotenv;
use Symfony\Component\Yaml\Yaml;

/**
 * Writes the configuration the test suites run against and removes it again afterwards.
 *
 * Framework-independent on purpose: the Playwright E2E tests call it through `Tests/test-environment.php`,
 * the PHPUnit bootstrap can call it directly.
 */
final class TestEnvironment
{
    public const CONFIG_YAML_FILE = 'config-test.yml';

    public const NOT_RUNNING_SERVER_DESC = 'Not Running Server';
    public const NOT_RUNNING_SERVER_HOST = '127.0.0.1';

    /**
     * Nothing listens on port 1, so a login attempt is refused immediately
     * instead of waiting for a TCP timeout against an unreachable host.
     */
    public const NOT_RUNNING_SERVER_PORT = 1;

    public const RUNNING_SERVER_DESC = 'Running Server';
    public const RUNNING_SERVER_DEFAULT_HOST = '127.0.0.1';
    public const RUNNING_SERVER_PORT = 5_432;

    /**
     * The settings both test configurations share, apart from the servers.
     */
    private const SETTINGS = [
        // The tests log in as "postgres", which extra login security refuses.
        'extra_login_security' => false,
        // Shows the advanced database tabs (Languages, Casts), so the E2E tests can reach them.
        'show_advanced' => true,
    ];

    /**
     * Writes the YAML configuration of the new pages and the PHP configuration of the legacy ones, which belongs to it
     * (see configIncPhpFile()). Neither touches a developer's own conf/config.yml or conf/config.inc.php.
     *
     * @param string $configYamlFile Relative to conf/. Processes running at the same time need different files,
     *                               otherwise one removes the configuration another one still reads.
     */
    public static function setUp(string $configYamlFile = self::CONFIG_YAML_FILE): void
    {
        Dotenv::createImmutable(self::rootDir())->safeLoad();

        $servers = self::servers(
            self::getEnvVar('PHPPGADMIN_TEST_SERVER_HOSTNAME') ?? self::RUNNING_SERVER_DEFAULT_HOST,
        );
        $configIncPhpFile = self::configIncPhpFile($configYamlFile);

        self::writeConfigYaml($configYamlFile, $servers);
        self::writeConfigIncPhp($configIncPhpFile, $servers);

        putenv('PHPPGADMIN_CONFIG_YAML_FILE=' . $configYamlFile);
        putenv('PHPPGADMIN_CONFIG_INC_PHP_FILE=' . $configIncPhpFile);
    }

    public static function tearDown(string $configYamlFile = self::CONFIG_YAML_FILE): void
    {
        foreach ([$configYamlFile, self::configIncPhpFile($configYamlFile)] as $configFile) {
            $configPath = self::confDir() . DIRECTORY_SEPARATOR . $configFile;

            if (file_exists($configPath)) {
                unlink($configPath);
            }
        }
    }

    /**
     * The PHP configuration of the legacy pages that belongs to a YAML configuration, e.g. config-test.inc.php for
     * config-test.yml. libraries/lib.inc.php reads it from PHPPGADMIN_CONFIG_INC_PHP_FILE.
     */
    public static function configIncPhpFile(string $configYamlFile): string
    {
        return pathinfo($configYamlFile, PATHINFO_FILENAME) . '.inc.php';
    }

    public static function getEnvVar(string $envName): ?string
    {
        if (isset($_ENV[$envName]) && is_string($_ENV[$envName])) {
            return $_ENV[$envName];
        }

        $envValue = getenv($envName);

        return is_string($envValue)
            ? $envValue
            : null;
    }

    /**
     * @return list<array{desc: string, host: string, port: int}>
     */
    private static function servers(string $runningServerHost): array
    {
        return [
            [
                'desc' => self::NOT_RUNNING_SERVER_DESC,
                'host' => self::NOT_RUNNING_SERVER_HOST,
                'port' => self::NOT_RUNNING_SERVER_PORT,
            ],
            [
                'desc' => self::RUNNING_SERVER_DESC,
                'host' => $runningServerHost,
                'port' => self::RUNNING_SERVER_PORT,
            ],
        ];
    }

    /**
     * @param list<array{desc: string, host: string, port: int}> $servers
     */
    private static function writeConfigYaml(string $configYamlFile, array $servers): void
    {
        $config = self::SETTINGS;
        $config['servers'] = $servers;

        self::writeConfigFile($configYamlFile, Yaml::dump($config));
    }

    /**
     * Takes the defaults from config.inc.php-dist, like a developer's own config.inc.php, and sets the servers and
     * settings of the YAML configuration.
     *
     * @param list<array{desc: string, host: string, port: int}> $servers
     */
    private static function writeConfigIncPhp(string $configIncPhpFile, array $servers): void
    {
        $lines = [
            '<?php',
            '',
            '// Generated by Tests\Support\TestEnvironment, removed after the test run.',
            "include __DIR__ . '/config.inc.php-dist';",
            '',
            '// Every server takes the defaults of the first one in config.inc.php-dist (sslmode, pg_dump_path, ...).',
            "\$defaultServer = \$conf['servers'][0];",
            "\$conf['servers'] = [];",
        ];

        foreach ($servers as $server) {
            $lines[] = "\$conf['servers'][] = array_merge(\$defaultServer, " . var_export($server, true) . ');';
        }

        $lines[] = 'unset($defaultServer);';

        foreach (self::SETTINGS as $name => $value) {
            $lines[] = "\$conf['{$name}'] = " . var_export($value, true) . ';';
        }

        self::writeConfigFile($configIncPhpFile, implode(PHP_EOL, $lines) . PHP_EOL);
    }

    private static function writeConfigFile(string $configFile, string $content): void
    {
        $configPath = self::confDir() . DIRECTORY_SEPARATOR . $configFile;

        if (file_put_contents($configPath, $content) === false) {
            throw new ConfigFileNotWrittenException("Failed to write {$configPath}");
        }
    }

    private static function confDir(): string
    {
        return self::rootDir() . DIRECTORY_SEPARATOR . 'conf';
    }

    private static function rootDir(): string
    {
        return dirname(__DIR__, 2);
    }
}
